import { lucia } from "$lib/server/auth";
import { sequence } from '@sveltejs/kit/hooks';
import { type Handle, redirect } from '@sveltejs/kit';
import { minify } from 'html-minifier';
import crypto from 'crypto';
import { db } from '$lib/server/db';
import { registers } from '$lib/server/db/schema';
import { eq } from 'drizzle-orm';

const md5 = (s: string) => crypto.createHash('md5').update(s).digest('hex');

// Saklar "wajib isi Surat Pernyataan saat login pertama" (sebelum ganti password).
const ENFORCE_FIRST_LOGIN_PERNYATAAN = true;

// Saklar fitur "wajib ganti password saat login pertama".
const ENFORCE_FIRST_LOGIN_PASSWORD_CHANGE = true;

const minifyHtml: Handle = async ({ event, resolve }) => {
  return resolve(event, {
    transformPageChunk: ({ html, done }) => {
      return minify(html, {
		caseSensitive: true,
		collapseBooleanAttributes: true,
		collapseInlineTagWhitespace: true,
		collapseWhitespace: true,
		conservativeCollapse: false,
		continueOnParseError: true,
		decodeEntities: true,
		html5: true,
		includeAutoGeneratedTags: true,
		keepClosingSlash: false,
		minifyCSS: true,
		minifyJS: true,
		minifyURLs: true,
		preserveLineBreaks: false,
		preventAttributesEscaping: false,
		processConditionalComments: true,
		removeAttributeQuotes: true,
		removeComments: true,
		removeEmptyAttributes: true,
		removeEmptyElements: true,
		removeOptionalTags: true,
		removeRedundantAttributes: true,
		removeScriptTypeAttributes: true,
		removeStyleLinkTypeAttributes: true,
		removeTagWhitespace: true,
		sortAttributes: true,
		sortClassName: true,
		trimCustomFragments: true,
		useShortDoctype: true,
	  
		/* NEW/EXTRA settings */
		customAttrAssign: [/\{[{%][^}]+[}%]\}/],      // enable collapsing custom templating attributes
		// customAttrSurround: [/\{\{[^}]+\}\}/],        // support templating expressions
		customEventAttributes: [/^on[a-z]{3,}$/],     // extreme: minify inline event‐handlers too
		quoteCharacter: '\'',                           // force single‐quote attributes where possible
		ignoreCustomComments: []                        // don't ignore any comments – we already removeComments=true
	  });
    }
  });
};

const luciaAuth: Handle = async ({ event, resolve }) => {
	const sessionId = event.cookies.get(lucia.sessionCookieName);
	if (!sessionId) {
		event.locals.user = null;
		event.locals.session = null;
	} else {
		const { session, user } = await lucia.validateSession(sessionId);
		if (session && session.fresh) {
			const sessionCookie = lucia.createSessionCookie(session.id);
			event.cookies.set(sessionCookie.name, sessionCookie.value, {
				path: "/",
				...sessionCookie.attributes
			});
		}
		if (!session) {
			const sessionCookie = lucia.createBlankSessionCookie();
			event.cookies.set(sessionCookie.name, sessionCookie.value, {
				path: "/",
				...sessionCookie.attributes
			});
		}
		event.locals.user = user;
		event.locals.session = session;
	}

	// Hitung "password masih default (== NIK)" di sini: locals.user.id = username
	// yang benar (Lucia memisahkannya dari attributes). Lalu HAPUS hash password
	// supaya tak ikut terkirim ke client via +layout.server.ts.
	if (event.locals.user) {
		const usr = event.locals.user as { id: string; password?: string; mustChangePassword: boolean };
		usr.mustChangePassword = typeof usr.password === 'string' && usr.password === md5(usr.id);
		delete usr.password;
	}

	return resolve(event);
};

const authGuard: Handle = async ({ event, resolve }) => {
	const protectedPaths = ['/dash', '/logout', '/-users/r', '/-doa', '/-logout'];
	const isProtected = protectedPaths.some((p) => event.url.pathname.startsWith(p));
	
	if (!event.locals.session && isProtected) {
		const isFetch = event.request.headers.get('accept')?.includes('application/json') || 
		                event.request.headers.get('x-sveltekit-action') === 'true';

		if (isFetch) {
			return new Response(JSON.stringify({ success: false, error: 'Session expired' }), {
				status: 401,
				headers: { 'content-type': 'application/json' }
			});
		}

		return new Response(null, {
            status: 303,
            headers: { location: "/login" }
        });
	}

	return resolve(event);
};

// Paksa isi Surat Pernyataan saat login pertama (SEBELUM ganti password).
// Penanda "sudah kirim" = ada baris di tabel registers utk NIK user.
const forcePernyataan: Handle = async ({ event, resolve }) => {
	if (!ENFORCE_FIRST_LOGIN_PERNYATAAN) return resolve(event);
	const u = event.locals.user;
	// Admin (userlevel -1) tidak perlu mengisi surat pernyataan.
	if (u && u.userlevel !== -1) {
		const path = event.url.pathname;
		const allowed =
			path === '/surat-pernyataan' ||
			path.startsWith('/-users/w') ||
			path.startsWith('/-logout');
		const guarded =
			path === '/' || ['/dash', '/-users/r', '/-doa'].some((p) => path.startsWith(p));

		if (guarded && !allowed) {
			const sudah = await db.query.registers.findFirst({ where: eq(registers.nik, u.id) });
			if (!sudah) {
				if (path.startsWith('/-')) {
					return new Response(
						JSON.stringify({ success: false, error: 'MUST_SUBMIT_PERNYATAAN' }),
						{ status: 403, headers: { 'content-type': 'application/json' } }
					);
				}
				return new Response(null, { status: 303, headers: { location: '/surat-pernyataan' } });
			}
		}
	}
	return resolve(event);
};

// Paksa ganti password saat login pertama (password masih default == NIK).
// mustChangePassword dihitung di getUserAttributes (auth.ts). Selama true, semua
// path aplikasi terlindungi dialihkan ke /change-password, kecuali halaman ganti
// password itu sendiri, endpoint-nya, dan logout.
const forcePasswordChange: Handle = async ({ event, resolve }) => {
	if (!ENFORCE_FIRST_LOGIN_PASSWORD_CHANGE) return resolve(event);
	const u = event.locals.user;
	// Admin (userlevel -1) tidak dipaksa ganti password.
	if (u && u.userlevel !== -1 && u.mustChangePassword) {
		const path = event.url.pathname;
		const allowed =
			path === '/change-password' ||
			path.startsWith('/-users/ganti-password') ||
			path.startsWith('/-logout');
		const guarded =
			path === '/' || ['/dash', '/-users/r', '/-doa'].some((p) => path.startsWith(p));

		if (guarded && !allowed) {
			// Endpoint aplikasi (konvensi prefix "/-") → 403 JSON; halaman → redirect.
			if (path.startsWith('/-')) {
				return new Response(
					JSON.stringify({ success: false, error: 'MUST_CHANGE_PASSWORD' }),
					{ status: 403, headers: { 'content-type': 'application/json' } }
				);
			}
			return new Response(null, { status: 303, headers: { location: '/change-password' } });
		}
	}
	return resolve(event);
};

export const handle: Handle = sequence(
	luciaAuth,
	authGuard,
	forcePernyataan,
	forcePasswordChange,
	minifyHtml
);
